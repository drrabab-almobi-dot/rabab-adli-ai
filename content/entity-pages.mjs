export function locationFinder(entities) {
  const placesByRegion = new Map();
  // Use location wording already present in court and notary names in this region.
  for (const { name, region } of entities) {
    const place = name.match(/^(?:المحكمة العامة|كتابة العدل)(?: (?:الأولى|الثانية|الثالثة))? (?:ب(?:مدينة |محافظة )?|في )(?:(?:ب?(?:شمال|جنوب|شرق|غرب) )?)([^()]+?)(?: بمنطقة | \(|$)/)?.[1]?.trim();
    // Some entries in these categories refer to another organization or to a whole region.
    if (!place || /^(?:المحكم|محكم|النيابة|الهيئة|منطقة|المنطقة|الجوف$)/.test(place)) continue;
    if (!placesByRegion.has(region)) placesByRegion.set(region, new Set());
    placesByRegion.get(region).add(place);
  }

  const patterns = new Map(Array.from(placesByRegion, ([region, places]) => {
    const alternatives = Array.from(places).sort((a, b) => b.length - a.length)
      .map((place) => place.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|');
    return [region, {
      withPreposition: new RegExp(`(?:^| )(?:ب?(?:شمال|جنوب|شرق|غرب) |ب(?:(?:مدينة|محافظة) )?|في )(${alternatives})$`),
      courtName: new RegExp(`(?:^| )ب?محكمة (${alternatives}) (?:العامة|الجزائية)(?: |$)`),
    }];
  }));
  return ({ name, region }) => {
    const pattern = patterns.get(region);
    if (!pattern) return null;
    const label = name.split('(')[0].split(' بمنطقة ')[0].trim();
    const place = label.match(pattern.withPreposition);
    return place?.[1] ?? label.match(pattern.courtName)?.[1] ?? null;
  };
}
